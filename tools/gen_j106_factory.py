def patches():
    raw = SRC.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SHA256 or len(raw) != 128 * 24:
        raise SystemExit(f"{SRC}: checksum or length changed (128 patch messages of 24 B)")
    out = []
    for k in range(128):
        m = raw[k * 24:(k + 1) * 24]
        if m[:5] != bytes([0xF0, 0x41, 0x30, 0, k]) or m[-1] != 0xF7 or any(x > 127 for x in m[1:-1]):
            raise SystemExit(f"{SRC}: patch {k + 1} is not the patch message of program {k}")
        out.append(m[5:-1])
    return out


def main(path):
    ps = patches()
    if len(NAMES) != 128:
        raise SystemExit(f"{len(NAMES)} names, want 128")
    names = [SHORT.get(n, n.upper()) for n in NAMES]
    for n in names:
        if len(n) > 12 or not all(32 <= ord(c) <= 126 for c in n):
            raise SystemExit(f"{n}: not 12 printable characters at most")
    L = ["/* generated by tools/gen_j106_factory.py from assets/j106-factory/j106-factory.syx:",
         " * Roland's 128 Juno-106 factory patches (A11 .. B88), each named and its sixteen sliders, SW1, SW2 */",
         "#define J106_FACTORY_N 128u",
         "static const struct { char name[J106_NAME_LEN + 1u]; uint8_t raw[J106_RAW]; } J106_FACTORY[128] = {"]
    L += [f'    {{"{n}", {{{",".join(map(str, p))}}}}},' for n, p in zip(names, ps)] + ["};"]
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    Path(path).write_text("\n".join(L) + "\n")
    print(f"j106 factory: {len(ps)} patches -> {path}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])

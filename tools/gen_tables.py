"""DSP lookup tables for MELODEE (integer controls and native fp32 synths).

FS = 44100 Hz, control rate = every CTL (32) samples. All curves map a
0..127 parameter value to the unit the DSP needs, plus a display table.
"""
import math
import struct
import sys
from pathlib import Path

FS = 44100
CTL = 32


def arr(name, ctype, vals, per=12, ram=False):
    """a table in flash (XIP, through the cache); ram: in RAM (.data), for lookups every sample"""
    out = [f"static {'TABLE_RAM ' if ram else 'const '}{ctype} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per):
        out.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    out.append("};")
    return out


def nibbles(steps, first):
    """steps (each 0..15) two per byte, low nibble first (dsp_tables_init adds them up from first)"""
    assert first == 0 and all(0 <= d < 16 for d in steps)
    out = [(steps + [0])[i] | (steps + [0])[i + 1] << 4 for i in range(0, len(steps), 2)]
    assert [out[i >> 1] >> (i & 1) * 4 & 15 for i in range(len(steps))] == steps
    return out


def f32(x):
    """x rounded to an IEEE single, as C stores a float"""
    return struct.unpack("f", struct.pack("f", x))[0]


def main(path):
    L = ["/* generated by tools/gen_tables.py */", "#pragma once", "#include <stdint.h>",
         f"#define FS {FS}", f"#define CTL {CTL}",
         "#if defined(__APPLE__) || !defined(__clang__) && !defined(__GNUC__)",
         "#define TABLE_RAM                 /* host builds: anywhere */",
         "#else",
         "#define TABLE_RAM __attribute__((section(\".data.tables\")))   /* RAM, not XIP flash: per-sample lookups */",
         "#endif", ""]
    # (1025 points: SINE[i + 1] needs no wrap; the users mask)
    L += arr("SINE", "int16_t", [int(round(32767 * math.sin(2 * math.pi * i / 1024))) for i in range(1025)])
    # phase increment for pitch in 1/16 semitone, MIDI 0..127
    inc = []
    for p in range(128 * 16):
        f = 440.0 * 2 ** ((p / 16 - 69) / 12)
        inc.append(min(int(f / FS * 2 ** 32), 0x7FFFFFFF))
    # stored as its top octave (1856..2047) shifted down: floor(floor(x) / 2^k) = floor(x / 2^k), so
    # pitch_inc(p) equals the 2048-entry table bit for bit (checked here); 7.4 KB less flash
    oct_ = inc[1856:2048]
    assert all(inc[q] == oct_[(q + 64) % 192] >> (10 - (q + 64) // 192) for q in range(2048))
    assert all((q + 64) * 21846 >> 22 == (q + 64) // 192 for q in range(2048))
    L += arr("PITCH_OCT", "uint32_t", oct_, 8)
    # Device concert pitch: exact frequency ratios and FM6's Q24 octave offsets.
    L += arr("A4_RATIO", "uint32_t", [round((1 << 24) * hz / 440) for hz in range(400, 481)], 8)
    L += arr("A4_LOG", "int32_t", [round((1 << 24) * math.log2(hz / 440)) for hz in range(400, 481)], 8)
    L += ["/* phase increment of pitch p in 1/16 semitone, 0..2047 (MIDI 0..127): 440 Hz * 2^((p / 16 - 69) / 12) */",
          "static inline uint32_t pitch_inc(uint32_t p)",
          "{",
          "    uint32_t i = p + 64u, o = (i * 21846u) >> 22;     /* i / 192: the octave above PITCH_OCT's - 10 */",
          "    return PITCH_OCT[i - o * 192u] >> (10u - o);",
          "}"]
    # times 1 ms .. 10 s (exponential), env in Q24 (1.0 = 1<<24)
    ms = [1.0 * (10000 ** (v / 127)) for v in range(128)]
    L += arr("TIME_MS_X10", "uint32_t", [int(round(m * 10)) for m in ms], 10)
    L += arr("ENV_LIN", "uint32_t", [max(1, int((1 << 24) * CTL / (m * FS / 1000))) for m in ms], 8)
    exp_k = []
    for m in ms:
        tau = m / 1000 / 4.6                       # ~99 % of the way after "m" ms
        exp_k.append(max(1, min(65535, int(65536 * (1 - math.exp(-CTL / (tau * FS)))))))
    L += arr("ENV_EXP", "uint16_t", exp_k)
    # LFO 0.05 .. 40 Hz, phase increment per control tick
    hz = [0.05 * (800 ** (v / 127)) for v in range(128)]
    L += arr("LFO_HZ_X100", "uint32_t", [int(round(h * 100)) for h in hz], 10)
    L += arr("LFO_INC", "uint32_t", [int(h * CTL / FS * 2 ** 32) for h in hz], 8)
    # filter cutoff 30 Hz .. 16 kHz
    fc = [30.0 * ((16000 / 30) ** (v / 127)) for v in range(128)]
    L += arr("CUTOFF_HZ", "uint16_t", [int(round(f)) for f in fc])
    # trapezoidal (Simper) SVF: g = tan(pi fc / FS), Q12; stable at any cutoff/resonance
    L += arr("SVF_G", "uint16_t", [int(4096 * math.tan(math.pi * min(f, 0.45 * FS) / FS)) for f in fc])
    L += ["#if !defined(MELODEE_PROPHET) || MELODEE_PROPHET"]
    L += [f"#define P5_KEYTRACK_HALF_Q7 {round(128 * 256 * 127 * math.log(2) / (2 * 192 * math.log(fc[-1] / fc[0])))}"]
    # LFO rate, raw 0..127. Measured on a Rev-4 factory demo (rates 74..97 -> 2.4..8.4 Hz,
    # within 2 %): ln Hz = -3.1005 + 0.05387 raw, bent at the ends to the documented .022 / 500 Hz.
    def p5_lfo_hz(v):
        x = -3.1005 + 0.05387 * v
        if v > 100:
            x += (math.log(500) - (-3.1005 + 0.05387 * 127)) * ((v - 100) / 27) ** 2
        if v < 20:
            x -= (-3.1005 - math.log(.022)) * ((20 - v) / 20) ** 2
        return math.exp(x)
    L += arr("P5_LFO_INC", "uint32_t", [int(p5_lfo_hz(v) / FS * 2**32) for v in range(128)], 8)
    # LFO amount response (initial + wheel + pressure), normalized. Rev-4 vibrato depth measured at
    # 18..55 fits 0.0519 * raw^1.737 cents; the full scale (235 cents) lives in the engine.
    L += arr("P5_AMOUNT", "float", [f"{(v / 127) ** 1.737:.9e}f" for v in range(128)])
    # Keep the calibrated times, without quantizing rates to Q24/Q16.
    p5ms = [10000 ** (v / 127) for v in range(128)]
    L += arr("P5_ENV_ATK", "float", [f"{CTL / (m * FS / 1000):.9e}f" for m in p5ms])
    L += arr("P5_ENV_EXP", "float", [f"{1 - math.exp(-CTL / (m / 1000 * FS)):.9e}f" for m in p5ms])
    L += arr("P5_ENV_SSM", "float", [f"{CTL / (3.6 * m * FS / 1000):.9e}f" for m in p5ms])
    # TPT coefficients at the selected oversampling rate. Keep this small
    # RAM table for audio-rate Poly-Mod; feedback division and tanh use fp32.
    for os in (2, 1):
        L += ["#if P5_OVERSAMPLE == 2" if os == 2 else "#else"]
        vals = [math.tan(math.pi * f / (os * FS)) / (1 + math.tan(math.pi * f / (os * FS))) for f in fc]
        g = arr("P5_TPT_G", "float", [f"{v:.9e}f" for v in vals])
        g[0] = g[0].replace(" =", ' __attribute__((section(".dsp_tables"))) =')
        L += g
    L += ["#endif"]  # oversampling
    tanh = arr("P5_TANH", "float", [f"{math.tanh(i / 128):.9e}f" for i in range(1025)])
    tanh[0] = tanh[0].replace(" =", ' __attribute__((section(".dsp_tables"))) =')
    L += tanh
    exp2 = arr("P5_EXP2", "float", [f"{2 ** (i / 512):.9e}f" for i in range(514)])
    exp2[0] = exp2[0].replace(" =", ' __attribute__((section(".dsp_tables"))) =')
    L += exp2
    L += ["#endif"]
    # level: 0 = off, else dB = (v - 112) / 2  (112 = 0 dB, 127 = +7.5 dB)
    db = [None] + [(v - 112) / 2 for v in range(1, 128)]
    L += arr("LEVEL_Q12", "uint16_t", [0] + [int(round(4096 * 10 ** (d / 20))) for d in db[1:]])
    L += arr("LEVEL_DB_X10", "int16_t", [-999] + [int(round(d * 10)) for d in db[1:]])
    # per-sample exponential decay for drum voices: 5 ms .. 4 s to -60 dB, Q16
    dms = [5.0 * (800 ** (v / 127)) for v in range(128)]
    L += arr("DECAY_K", "uint16_t", [min(65535, int(65536 * math.exp(-6.9 / (m / 1000 * FS)))) for m in dms])
    # soft clip curve for |x| in 0..2 (Q12 in, Q15 out): tanh
    tanh_q15 = arr("TANH_Q15", "int16_t", [int(32767 * math.tanh(i / 256 * 2)) for i in range(257)])
    tanh_q15[0] = tanh_q15[0].replace(" =", ' __attribute__((section(".dsp_tables"))) =')
    L += tanh_q15
    L += fm6_tables()
    Path(path).write_text("\n".join(L) + "\n")
    print(f"tables: {path}")




def lz_pack(t, start=0):
    """dsp.c lz_unpack's format: c < 0x80: c + 1 bytes follow; c >= 0x80: (c & 0x7f) + 3 bytes copied from
    d + 1 back, d in the next two bytes (little endian). Greedy longest match. t[:start] is a dictionary the
    decoder has in place before its output: only t[start:] is coded, its copies may reach back into it"""
    out, lit, i = bytearray(), bytearray(), start

    def flush():
        while lit:
            k = min(len(lit), 128)
            out.append(k - 1)
            out.extend(lit[:k])
            del lit[:k]
    while i < len(t):
        best, dist = 0, 0
        for d in range(1, min(i, 4096) + 1):
            n = 0
            while n < 130 and i + n < len(t) and t[i + n] == t[i + n - d]:
                n += 1
            if n > best:
                best, dist = n, d
                if n == 130:
                    break
        if best >= 3:
            flush()
            out += bytes([0x80 | (best - 3), (dist - 1) & 0xff, (dist - 1) >> 8])
            i += best
        else:
            lit.append(t[i])
            i += 1
    flush()
    return bytes(out)


def lz_unpack(b, n, dictionary=b""):
    o, i = bytearray(dictionary), 0
    while len(o) < len(dictionary) + n:
        c = b[i]
        if c < 0x80:
            o += b[i + 1:i + c + 2]
            i += c + 2
        else:
            d = b[i + 1] + (b[i + 2] << 8) + 1
            for _ in range((c & 0x7f) + 3):
                o.append(o[-d])
            i += 3
    return bytes(o[len(dictionary):])


def fm6_tables():
    """MSFA sine/frequency/LFO/portamento data (Apache-2.0).

    Sources and pinned revisions: docs/BLE_MIGRATION.md. No MARK I/OPL ROMs.
    """
    N = 64
    L = [f"#define FM6_N {N}", "#define FM6_LG_N 6"]
    # sine, Q24 out of a Q24 phase: 1024 points by rotation (sin.cc), the next point for interpolation
    # The normalized sine is filled at boot from two rotation constants.
    c = math.floor(math.cos(2 * math.pi / 1024) * (1 << 30) + 0.5)
    s = math.floor(math.sin(2 * math.pi / 1024) * (1 << 30) + 0.5)
    u, v, sin_t = 1 << 30, 0, [0] * 1025
    for i in range(512):
        sin_t[i] = (v + 32) >> 6
        sin_t[i + 512] = -((v + 32) >> 6)
        u, v = (u * c - v * s + (1 << 29)) >> 30, (u * s + v * c + (1 << 29)) >> 30
    assert all(abs(x) <= 1 << 24 and f32(x / 2**24) == x / 2**24 for x in sin_t)   # (float)x * 2^-24 is exact
    L += [f"#define FM6_SIN_C {c}", f"#define FM6_SIN_S {s}", "static float FM6_SIN[1025];"]
    # Exact integer phase steps for Q24 log pitches (Freqlut). The continuous
    # signal path is float, but float cannot carry every bit of this pitch.
    y, inc, fl = float(1 << 44) / FS, math.pow(2, 1.0 / 1024), []
    for i in range(1025):
        fl.append(math.floor(y + 0.5))
        y *= inc
    L += arr("FM6_FREQ", "int32_t", fl, 8)
    L += ["/* Fill the sine before any render; host builds also initialize it before main. */",
          "static void dsp_tables_init(void)",
          "{",
          "    int32_t u = 1 << 30, v = 0, x;",
          "    uint32_t i;",
          "    for (i = 0; i < 512u; i++) {",
          "        x = (v + 32) >> 6;",
          "        FM6_SIN[i] = (float)x * (1.0f / 16777216.0f);",
          "        FM6_SIN[i + 512u] = (float)-x * (1.0f / 16777216.0f);",
          "        x = (int32_t)(((int64_t)u * FM6_SIN_C - (int64_t)v * FM6_SIN_S + (1 << 29)) >> 30);",
          "        v = (int32_t)(((int64_t)u * FM6_SIN_S + (int64_t)v * FM6_SIN_C + (1 << 29)) >> 30);",
          "        u = x;",
          "    }",
          "    FM6_SIN[1024] = 0.0f;",
          "}",
          "#if defined(__APPLE__)",
          "__attribute__((constructor)) static void dsp_tables_ctor(void) { dsp_tables_init(); }",
          "#endif"]
    # frequency: coarse ratios, fine (dx7note.cc osc_freq), detune per note x (DET - 7) in Q24 fractions
    L += arr("FM6_COARSE", "int32_t", [-(1 << 24)] + [int(round((1 << 24) * math.log2(k))) for k in range(1, 32)], 8)
    L += arr("FM6_FINE", "int32_t", [math.floor(24204406.323123 * math.log(1 + 0.01 * f) + 0.5) for f in range(128)], 8)
    det = []
    for n in range(128):
        lf = 50857777 + ((1 << 24) // 12) * n                       # Dexed's standard tuning
        r = 0.0209 * math.exp(-0.396 * (f32(float(lf)) / (1 << 24))) / 7
        det.append(round(r * lf * (1 << 24)))
        for d in range(16):                                          # the table gives Dexed's result
            want = int(lf + r * lf * (d - 7)) - lf
            assert lf + ((det[-1] * (d - 7)) >> 24) - lf == want, (n, d)
    L += arr("FM6_DETUNE", "int64_t", det, 6)
    # LFO speeds (lfo.cc): Hz measured on a DX7 (MSFA, Copyright 2012 Google Inc.), as Dexed's phase
    # increments per 64-sample block
    hz = [0.062541, 0.125031, 0.312393, 0.437120, 0.624610, 0.750694, 0.936330, 1.125302, 1.249609, 1.436782,
          1.560915, 1.752081, 1.875117, 2.062494, 2.247191, 2.374451, 2.560492, 2.686728, 2.873976, 2.998950,
          3.188013, 3.369840, 3.500175, 3.682224, 3.812065, 4.000800, 4.186202, 4.310716, 4.501260, 4.623209,
          4.814636, 4.930480, 5.121901, 5.315191, 5.434783, 5.617346, 5.750431, 5.946717, 6.062811, 6.248438,
          6.431695, 6.564264, 6.749460, 6.868132, 7.052186, 7.250580, 7.375719, 7.556294, 7.687577, 7.877738,
          7.993605, 8.181967, 8.372405, 8.504848, 8.685079, 8.810573, 8.986341, 9.122423, 9.300595, 9.500285,
          9.607994, 9.798158, 9.950249, 10.117361, 11.251125, 11.384335, 12.562814, 13.676149, 13.904338,
          15.092062, 16.366612, 16.638935, 17.869907, 19.193858, 19.425019, 20.833333, 21.034918, 22.502250,
          24.003841, 24.260068, 25.746653, 27.173913, 27.578599, 29.052876, 30.693677, 31.191516, 32.658393,
          34.317090, 34.674064, 36.416606, 38.197097, 38.550501, 40.387722, 40.749796, 42.625746, 44.326241,
          44.883303, 46.772685, 48.590865, 49.261084]
    assert len(hz) == 100
    ratio = int(4437500000.0 * N / FS)
    L += arr("FM6_LFO_INC", "uint32_t", [int(h * ratio) for h in hz], 8)
    L += [f"#define FM6_LFO_UNIT {int(N * 25190424 / FS + 0.5)}",
          f"#define FM6_PEG_UNIT {int(N * (1 << 24) / (21.3 * FS) + 0.5)}"]
    # portamento (porta.cpp): pitch steps per block, plain and glissando, for CC 5 = 0..127
    def porta(sps):
        return [int(0.5 + ((1 << 24) // 12) * (sps * math.pow(2.0, -0.062 * i) / FS * N)) for i in range(128)]
    L += arr("FM6_PORTA", "int32_t", porta(2100.0), 8)
    L += arr("FM6_GLISS", "int32_t", porta(1300.0), 8)
    return L


if __name__ == "__main__":
    main(sys.argv[1])
